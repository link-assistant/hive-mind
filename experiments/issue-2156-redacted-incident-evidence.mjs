// Issue #2156 — produce a *redacted* evidence extract from the incident log.
//
// The log published to the gist contains a real (now revoked) GitHub OAuth user
// access token. Committing it — even revoked — would trip GitHub secret
// scanning on this repository, which is the very failure this issue is about.
// So nothing this script writes may contain the payload:
//
//   * masked spans are copied from the sanitizer's own output, so what lands in
//     the file is already the `abc…xyz` form the debug contract allows;
//   * the surrounding record is reduced to its *shape* — every base64-alphabet
//     run of 20+ characters becomes `<BASE64 len=N>` and every recognisable
//     token becomes `<TOKEN>` — and then sanitized again for good measure.
//
// The result is asserted clean by findCredentialResiduals before it is written,
// so a redaction rule that stops covering some future log fails loudly instead
// of silently emitting a file that has to be scrubbed by hand.
//
// Usage: node experiments/issue-2156-redacted-incident-evidence.mjs <logPath> [outPath]

import { readFileSync, writeFileSync } from 'node:fs';
import { sanitizeCredentialText, findCredentialResiduals } from '../src/credential-sanitization-core.lib.mjs';

const logPath = process.argv[2] ?? '/tmp/incident-2156.log';
const outPath = process.argv[3];

const text = readFileSync(logPath, 'utf8');
const sanitized = sanitizeCredentialText(text);
const before = text.split('\n');
const after = sanitized.split('\n');

// Reduce a raw line to its shape. Order matters: the token patterns are checked
// first so a `ghs_…` inside a longer run is reported as a token rather than
// swallowed by the generic base64 rule.
const toShape = line => sanitizeCredentialText(line.replace(/\b(gh[pousr]|github_pat)_[A-Za-z0-9_]{10,}/g, '<TOKEN>').replace(/[A-Za-z0-9+/_-]{20,}={0,2}/g, match => `<BASE64 len=${match.length}>`));

// A masked span is either the fixed `[REDACTED]` marker or a `abc…xyz` ellipsis
// form. Quotes and backslashes bound it because these records are escaped JSON.
const MASKED_SPAN = /(?:\[REDACTED\]|[^\s"\\]*…[^\s"\\]*)/g;

const sections = [];
for (let index = 0; index < Math.max(before.length, after.length); index += 1) {
  if (before[index] === after[index]) continue;
  const line = after[index] ?? '';
  const spans = [...line.matchAll(MASKED_SPAN)].map(match => `    …${line.slice(Math.max(0, match.index - 70), match.index)}»»${match[0]}««`);
  sections.push([`--- line ${index + 1} (${(before[index] ?? '').length} bytes) ---`, `  shape:`, `    ${toShape(before[index] ?? '').slice(0, 700)}`, `  masked spans (${spans.length}):`, ...spans, ''].join('\n'));
}

const report = ['# Redacted extract of the leaked log (issue #2156)', '#', '# Generated by experiments/issue-2156-redacted-incident-evidence.mjs.', '# Every credential below is shown in the masked form the sanitizer now', '# produces; the raw payload is deliberately absent from this repository.', '#', `# source lines:          ${before.length}`, `# source bytes:          ${text.length}`, `# lines changed:         ${sections.length}`, `# line count preserved:  ${before.length === after.length}`, '', ...sections].join('\n');

const residuals = findCredentialResiduals(report);
if (residuals.length > 0) {
  console.error('REFUSING TO WRITE: redacted report still carries credential residuals:', residuals);
  process.exit(1);
}

if (outPath) {
  writeFileSync(outPath, report);
  console.log(`wrote ${outPath} (${report.length} bytes, ${sections.length} changed lines)`);
} else {
  console.log(report);
}
