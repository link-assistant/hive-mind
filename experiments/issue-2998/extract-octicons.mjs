// Write src/github-octicons.lib.mjs: the 16px Primer Octicons the access animation draws.
// Usage: npm pack @primer/octicons@19.40.0 && tar -xzf primer-octicons-19.40.0.tgz
//        node experiments/issue-2998/extract-octicons.mjs package/build/data.json
import { readFileSync, writeFileSync } from 'node:fs';

const NAMES = ['mark-github', 'three-bars', 'search', 'triangle-down', 'plus', 'issue-opened', 'git-pull-request', 'inbox', 'code', 'play', 'table', 'book', 'shield', 'graph', 'gear', 'people', 'person', 'repo', 'organization', 'x', 'git-branch', 'tag', 'webhook', 'server', 'browser', 'report', 'checklist', 'copilot', 'lock', 'globe', 'mail'];
const data = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const entries = NAMES.map(name => {
  const path = data[name]?.heights?.['16']?.path;
  if (!path) throw new Error(`missing octicon ${name}`);
  return `  '${name}': '${path.replace(/'/g, "\\'")}',`;
});
writeFileSync(
  new URL('../../src/github-octicons.lib.mjs', import.meta.url),
  `/**
 * 16px Primer Octicons (https://github.com/primer/octicons, v19.40.0, MIT
 * License, Copyright (c) GitHub Inc.) drawn by the GitHub access animation.
 *
 * Generated by experiments/issue-2998/extract-octicons.mjs; do not edit.
 */

export const OCTICON_PATHS = Object.freeze({
${entries.join('\n')}
});

/**
 * Inline SVG for an octicon (valid XHTML, so it also works inside an SVG
 * foreignObject).
 *
 * @param {string} name
 * @param {Object} [options]
 * @param {number} [options.size=16]
 * @param {string} [options.className='oi']
 * @returns {string}
 */
export function octicon(name, { size = 16, className = 'oi' } = {}) {
  const path = OCTICON_PATHS[name];
  if (!path) throw new Error(\`Unknown octicon: \${name}\`);
  return \`<svg xmlns="http://www.w3.org/2000/svg" class="\${className}" width="\${size}" height="\${size}" viewBox="0 0 16 16" fill="currentColor" aria-hidden="true">\${path}</svg>\`;
}
`
);
console.log(`${NAMES.length} octicons written`);
